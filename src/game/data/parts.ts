export const PARTS: Record<string, PartDef> = Object.fromEntries(PART_LIST.map((p) => [p.id, p]));

export function getDef(id: string): PartDef {
  const d = PARTS[id];
  if (!d) throw new Error(`Unknown part id: ${id}`);
  return d;
}

